#!/bin/sh
# DKMS PRE_BUILD step for the packaged Quark kernel module.
#
# The module only honors netlink commands that are (1) sent by the exact
# quark_cli binary it was built against (SHA-256 check) and (2) signed with the
# private key matching its embedded public key. A distro package can't ship a
# shared private key (every user could extract it), so each machine gets its
# own: generated here on the first build, then reused across kernel upgrades so
# every rebuilt module keeps trusting the same key.
#
# Writes into this script's directory (the DKMS build tree):
#   quark_pubkey.h    -- public half of the machine key
#   quark_cli_hash.h  -- SHA-256 of the installed quark_cli
# Header formats mirror tooling/keys/generate-testing-key.sh and the top-level
# Makefile's kernel/quark_cli_hash.h rule.

set -eu

QUARK_CLI="${QUARK_CLI:-/usr/lib/quark-anticheat/quark_cli}"
KEY="${QUARK_SIGNING_KEY:-/etc/quark-anticheat/quark_signing_key.pem}"
OUT_DIR="$(dirname "$0")"

die() {
    echo "quark-dkms-prebuild: $*" >&2
    exit 1
}

# "0x01,0x02,..." from raw bytes on stdin.
to_c_bytes() {
    od -An -v -tx1 | tr -s ' \n' ' ' | sed 's/^ //;s/ $//;s/\([0-9a-f][0-9a-f]\)/0x\1/g;s/ /,/g'
}

[ -x "$QUARK_CLI" ] || die "$QUARK_CLI not found or not executable"
command -v openssl >/dev/null 2>&1 || die "openssl is required"

if [ ! -f "$KEY" ]; then
    echo "quark-dkms-prebuild: generating per-machine signing key $KEY"
    key_dir="$(dirname "$KEY")"
    mkdir -p "$key_dir"
    chmod 700 "$key_dir"
    # Create the file 0600 before any key material is written to it.
    (umask 077 && openssl ecparam -name prime256v1 -genkey -noout -out "$KEY") ||
        die "failed to generate $KEY"
fi

# The SubjectPublicKeyInfo DER of a P-256 key ends with the raw 65-byte SEC1
# uncompressed point the kernel's x962(ecdsa-nist-p256) verifier expects.
pubkey_bytes="$(openssl ec -in "$KEY" -pubout -outform DER 2>/dev/null | tail -c 65 | to_c_bytes)" ||
    die "failed to read public key from $KEY"
[ -n "$pubkey_bytes" ] || die "empty public key read from $KEY"

cli_hash_bytes="$(sha256sum "$QUARK_CLI" | cut -d' ' -f1 | sed 's/../0x&,/g;s/,$//')"

cat >"$OUT_DIR/quark_pubkey.h" <<EOF
/* Auto-generated by quark-dkms-prebuild.sh from $KEY -- DO NOT hand-edit. */
#ifndef QUARK_PUBKEY_H
#define QUARK_PUBKEY_H

/* Raw SEC1 uncompressed ECDSA P-256 public key point (0x04 || X || Y). */
static const unsigned char quark_pubkey[65] = {$pubkey_bytes};

#endif /* QUARK_PUBKEY_H */
EOF

cat >"$OUT_DIR/quark_cli_hash.h" <<EOF
/* Auto-generated by quark-dkms-prebuild.sh from $QUARK_CLI -- DO NOT hand-edit. */
#ifndef QUARK_CLI_HASH_H
#define QUARK_CLI_HASH_H
static const unsigned char quark_cli_expected_sha256[32] = {$cli_hash_bytes};
#endif
EOF
